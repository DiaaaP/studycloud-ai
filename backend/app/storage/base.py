from __future__ import annotations

from typing import Any, Callable, Protocol, TypeVar


Row = dict[str, Any]
T = TypeVar("T")


class UserRepository(Protocol):
    def get_by_id(self, user_id: str) -> Row | None: ...
    def get_by_username(self, username: str) -> Row | None: ...
    def count(self) -> int: ...
    def create(self, user: Row) -> Row: ...
    def claim_legacy_records(self, user_id: str) -> None: ...


class LectureRepository(Protocol):
    def get_visible(self, lecture_id: str, user_id: str) -> Row | None: ...
    def get_owned(self, lecture_id: str, user_id: str) -> Row | None: ...
    def list_visible(self, user_id: str) -> list[Row]: ...
    def create(self, lecture: Row) -> Row: ...
    def update_owned(
        self, lecture_id: str, user_id: str, values: Row
    ) -> Row | None: ...
    def delete_owned(self, lecture_id: str, user_id: str) -> bool: ...
    def count_for_user(self, user_id: str) -> Row: ...


class QuizAttemptRepository(Protocol):
    def create(self, attempt: Row) -> Row: ...
    def get_stats(self, user_id: str) -> Row: ...


class KnowledgeGapRepository(Protocol):
    def get(
        self, user_id: str, lecture_id: str, concept: str
    ) -> Row | None: ...
    def upsert(self, gap: Row) -> Row: ...
    def get_by_id(self, gap_id: int, user_id: str) -> Row | None: ...
    def list_for_user(self, user_id: str) -> list[Row]: ...
    def update_review(
        self, gap_id: int, user_id: str, values: Row
    ) -> Row | None: ...
    def count_open(self, user_id: str) -> int: ...
    def count_blind_spots(self, user_id: str) -> int: ...


class UnitOfWork(Protocol):
    users: UserRepository
    lectures: LectureRepository
    quiz_attempts: QuizAttemptRepository
    knowledge_gaps: KnowledgeGapRepository


class Storage(Protocol):
    def initialize(self) -> None: ...

    def run_transaction(
        self, operation: Callable[[UnitOfWork], T]
    ) -> T: ...

    def close(self) -> None: ...
